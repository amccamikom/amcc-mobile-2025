void main() {
  // int
  int year = 2026;
  print(year);

  // double
  double pi = 3.14;
  print(pi);

  // num
  num temperature = 36.6;
  num score = 95;
  print(temperature);
  print(score);

  // String
  String greeting = "We Are Mobile Rangers";
  print(greeting);

  // bool
  bool isLoggedIn = true;
  bool hasSubscription = false;
  print(isLoggedIn);
  print(hasSubscription);

  // map
  Map<String, int> studentScores = {
    'Alice': 85,
    'Bob': 92,
    'Charlie': 78,
  };
  print(studentScores);

  // list
  List<String> fruits = ['Apple', 'Banana', 'Cherry'];
  print(fruits);

  // dynamic
  dynamic variable = "I am a string";
  print(variable);
}

